"""Generate review scripts. Nothing here talks to a server.

The DROP script has every statement commented out; the rollback script, which
recreates the dropped indexes, does not.
"""
import re

from . import __version__
from .analysis import CONSOLIDATE, DROP
from .sqlnames import quote_name

HEADER = """-- Generated by index-advisor {version} for {server}, database {database}, on {when}.
-- REVIEW BEFORE RUNNING. index-advisor never changes the server; this file is only a proposal.
"""


def safe_filename(name):
    return re.sub(r"[^A-Za-z0-9_.-]", "_", name)


def one_line(text):
    """Make text safe for a -- comment: a newline would end the comment."""
    return re.sub(r"[\r\n]+", " ", text)


def table_ref(ix):
    return "%s.%s" % (quote_name(ix.schema), quote_name(ix.table))


def drop_statement(ix):
    return "DROP INDEX %s ON %s;" % (quote_name(ix.name), table_ref(ix))


def _storage_clause(ix):
    """ON <partition scheme>(<column>) or ON <filegroup>, so a recreated index lands where it was."""
    if ix.data_space_type == "PS" and ix.data_space and ix.partition_column:
        return " ON %s(%s)" % (quote_name(ix.data_space), quote_name(ix.partition_column))
    if ix.data_space_type == "FG" and ix.data_space and not ix.data_space_is_default:
        return " ON %s" % quote_name(ix.data_space)
    return ""


def create_statement(ix, includes=None, drop_existing=False):
    """CREATE INDEX for a rowstore nonclustered index.

    Only the keys, includes, filter and fill factor are rebuilt from metadata;
    see the notes in the generated scripts for what is not captured.
    """
    unique = "UNIQUE " if ix.is_unique else ""
    kind = "CLUSTERED " if ix.type_desc == "CLUSTERED" else "NONCLUSTERED "
    sql = "CREATE %s%sINDEX %s ON %s (%s)" % (
        unique, kind, quote_name(ix.name), table_ref(ix), ", ".join(c.sql() for c in ix.keys))
    columns = ix.includes if includes is None else includes
    if columns:
        sql += " INCLUDE (%s)" % ", ".join(quote_name(c) for c in columns)
    if ix.filter_definition:
        sql += " WHERE " + ix.filter_definition
    options = []
    if ix.fill_factor:
        options.append("FILLFACTOR = %d" % ix.fill_factor)
    if ix.compression in ("ROW", "PAGE"):
        options.append("DATA_COMPRESSION = %s" % ix.compression)
    if drop_existing:
        options.append("DROP_EXISTING = ON")
    if options:
        sql += " WITH (%s)" % ", ".join(options)
    return sql + _storage_clause(ix) + ";"


def _header(analysis, server):
    return HEADER.format(version=__version__, server=server.server_name or "(unknown)",
                         database=quote_name(analysis.database), when=server.now.strftime("%Y-%m-%d %H:%M"))


def drop_candidates(analysis):
    return [r for r in analysis.recommendations if r.action == DROP]


def drop_script(analysis, server):
    recs = drop_candidates(analysis)
    lines = [
        _header(analysis, server).rstrip("\n"),
        "-- Every DROP statement below is commented out. Remove the leading '-- ' from the ones you accept.",
        "-- Before dropping:",
        "--   * search code, jobs and plan guides for INDEX hints that name these indexes; they fail once the index is gone",
        "--   * keep the matching recreate-dropped.sql so the change can be undone",
    ]
    for warning in analysis.warnings:
        lines.append("--")
        lines.append("-- WARNING: " + one_line(warning))
    lines += ["", "USE %s;" % quote_name(analysis.database), "GO", ""]
    for rec in recs:
        ix = rec.index
        lines.append("-- %s (%.1f MB)" % (one_line(ix.full_name), ix.size_mb))
        for reason in rec.reasons:
            lines.append("--   - " + one_line(reason))
        lines.append("-- " + drop_statement(ix))
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def recreate_script(analysis, server):
    recs = drop_candidates(analysis)
    lines = [
        _header(analysis, server).rstrip("\n"),
        "-- Rollback: recreates the indexes listed in drop-candidates.sql from the metadata read at the time.",
        "-- Captured: keys, included columns, filter, fill factor, filegroup or partition scheme, and uniform",
        "-- data compression. Not captured: per-partition compression and other WITH options. Compare with the",
        "-- original definition (for example scripted from SSMS) before relying on this for a large table.",
        "",
        "USE %s;" % quote_name(analysis.database),
        "GO",
        "",
    ]
    for rec in recs:
        lines.append("-- %s" % one_line(rec.index.full_name))
        if rec.index.compression == "MIXED":
            lines.append("-- NOTE: the partitions use different compression settings; set DATA_COMPRESSION per partition.")
        lines.append(create_statement(rec.index))
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def generate_scripts(report):
    """{filename: text} for every database that has something to propose."""
    files = {}
    for analysis in report.databases:
        stem = safe_filename(analysis.database)
        if drop_candidates(analysis):
            files[stem + ".drop-candidates.sql"] = drop_script(analysis, report.server)
            files[stem + ".recreate-dropped.sql"] = recreate_script(analysis, report.server)
        if merge_plans(analysis):
            files[stem + ".consolidate.sql"] = consolidate_script(analysis, report.server)
        if analysis.suggestions:
            files[stem + ".missing-indexes.sql"] = missing_script(analysis, report.server)
    return files


def merge_plans(analysis):
    """[(target recommendation, [source recommendations])] for consolidations."""
    plans = []
    for target in analysis.recommendations:
        if not target.merge_includes:
            continue
        sources = [r for r in analysis.recommendations
                   if r.action == CONSOLIDATE and r.related and r.related[0] == target.index.name
                   and r.index.table == target.index.table and r.index.schema == target.index.schema]
        if sources:
            plans.append((target, sources))
    return plans


def consolidate_script(analysis, server):
    lines = [
        _header(analysis, server).rstrip("\n"),
        "-- Consolidation: widen a kept index with the included columns of an index that is a left prefix of it,",
        "-- then drop the narrower one. Every statement is commented out; remove the leading '-- ' from the",
        "-- ones you accept, and run the steps of one block in order. Rebuilding the target locks or scans the",
        "-- whole index, so schedule it for a quiet period.",
        "",
        "USE %s;" % quote_name(analysis.database),
        "GO",
        "",
    ]
    for target, sources in merge_plans(analysis):
        ix = target.index
        merged = ix.includes + [c for c in target.merge_includes if c.lower() not in {i.lower() for i in ix.includes}]
        lines.append("-- Merge into %s (%.1f MB)" % (one_line(ix.full_name), ix.size_mb))
        for source in sources:
            lines.append("--   from %s (%.1f MB)" % (one_line(source.index.full_name), source.index.size_mb))
        lines.append("-- 1. add the missing included columns to the kept index")
        lines.append("-- " + create_statement(ix, includes=merged, drop_existing=True))
        lines.append("-- 2. drop the merged index(es)")
        for source in sources:
            lines.append("-- " + drop_statement(source.index))
        lines.append("-- Rollback")
        lines.append("--   " + create_statement(ix, drop_existing=True))
        for source in sources:
            lines.append("--   " + create_statement(source.index))
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def new_index_statement(suggestion):
    sql = "CREATE NONCLUSTERED INDEX %s ON %s.%s (%s)" % (
        quote_name(suggestion.name), quote_name(suggestion.missing.schema), quote_name(suggestion.missing.table),
        ", ".join(quote_name(k) for k in suggestion.keys))
    if suggestion.includes:
        sql += " INCLUDE (%s)" % ", ".join(quote_name(c) for c in suggestion.includes)
    return sql + ";"


def missing_script(analysis, server):
    lines = [
        _header(analysis, server).rstrip("\n"),
        "-- Suggestions from the missing-index DMVs. They are based on single query plans, ignore the other",
        "-- indexes on the table, and are cleared by a restart or a change to the table. Treat them as hints:",
        "-- compare them with the existing indexes, create at most one index per table at a time, and measure",
        "-- the effect on writes. Every statement is commented out.",
        "",
        "USE %s;" % quote_name(analysis.database),
        "GO",
        "",
    ]
    for s in analysis.suggestions:
        m = s.missing
        lines.append("-- %s.%s: score %s, %s uses, average cost %.1f, average impact %.0f%%" % (
            one_line(m.schema), one_line(m.table), format(round(s.score), ","), format(m.seeks + m.scans, ","),
            m.avg_cost, m.avg_impact))
        for note in s.notes:
            lines.append("--   " + one_line(note))
        if s.extends is None:
            lines.append("-- " + new_index_statement(s))
        elif s.add_columns:
            widened = s.extends.includes + s.add_columns
            lines.append("-- " + create_statement(s.extends, includes=widened, drop_existing=True))
            lines.append("-- Rollback: " + create_statement(s.extends, drop_existing=True))
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"
